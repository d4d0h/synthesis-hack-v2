/**
 * Setup Wallets — Generate keypairs for TrustVault and Peer agents
 */
import { generatePrivateKey, privateKeyToAccount } from "viem/accounts";
import { writeFileSync, existsSync } from "fs";

console.log("=== TrustVault Wallet Setup ===\n");

// Generate agent wallet
const agentKey = generatePrivateKey();
const agentAccount = privateKeyToAccount(agentKey);
console.log("Agent (TrustVault):");
console.log(`  Address:     ${agentAccount.address}`);
console.log(`  Private Key: ${agentKey}`);

// Generate peer wallet
const peerKey = generatePrivateKey();
const peerAccount = privateKeyToAccount(peerKey);
console.log("\nPeer (VerifyBot):");
console.log(`  Address:     ${peerAccount.address}`);
console.log(`  Private Key: ${peerKey}`);

// Write to .env if it doesn't exist
const envPath = "../../.env";
if (!existsSync(envPath)) {
  const envContent = `# Generated by setup-wallets.ts
AGENT_PRIVATE_KEY=${agentKey}
PEER_PRIVATE_KEY=${peerKey}

# Fill in these values:
ANTHROPIC_API_KEY=sk-ant-...
VENICE_API_KEY=
CHAIN_RPC_URL=https://sepolia.infura.io/v3/YOUR_KEY
IDENTITY_REGISTRY=
REPUTATION_REGISTRY=
SYNTH_API_KEY=
`;
  writeFileSync(envPath, envContent);
  console.log(`\n.env created at ${envPath}`);
} else {
  console.log("\n.env already exists — add the keys manually.");
}

console.log("\nNext steps:");
console.log("1. Fund the agent address with testnet ETH:");
console.log(`   https://sepoliafaucet.com/`);
console.log("2. Set API keys in .env");
console.log("3. Run: npm run register");
